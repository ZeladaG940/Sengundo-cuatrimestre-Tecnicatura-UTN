#las tuplas son listas inmutables osea que no pueden cambiar su valor
tupla = (1,2,3,4,5,6)
print(tupla)

#acceder a un elemto en una tupla
print(tupla[0])

#como invertir una tupla
print(tupla[-1])

#como acceder a u rango en una tupla
print(tupla[0:5])

#como recorrer elemntos en una tupla
for i in tupla:
    print(i)

