#tipo set
set = {1,2,3,4,5,6}
print(set)

#como saber la longitud de algo
print(len(set))

#como saber si un elemto existe en un listado
print(2 in set)

#como agregar elemtos a un set
set.add(7)
print(set)

#como elminar un elemto
set.remove(7)
print(set)

#como limpiar el set
set.clear()
print(set)

#como eliminar un set
del set
print(set)